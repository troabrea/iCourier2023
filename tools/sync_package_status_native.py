#!/usr/bin/env python3
"""Generate native status rules from the canonical Dart mapper's term sets."""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lib/domain/package_stage.dart'


def terms(name):
    block = re.search(rf'static const _{name}Terms = <String>{{(.*?)\n  }};', SOURCE.read_text(), re.S)[1]
    return re.findall(r"^    '([^']+)',", block, re.M)


def generate():
    sets = {name: terms(name) for name in ['delivered', 'destination', 'route', 'origin']}
    swift_sets = '\n'.join(f'  private static let {name}Terms: Set<String> = [{", ".join(json.dumps(v) for v in values)}]' for name, values in sets.items())
    kotlin_sets = '\n'.join(f'    private val {name}Terms = setOf({", ".join(json.dumps(v) for v in values)})' for name, values in sets.items())
    swift = '''// Generated by tools/sync_package_status_native.py. Edit the Dart mapper.
import Foundation

enum RemotePackageStage: String {
  case origin = "origen"
  case route = "ruta"
  case destination = "destino"
  case available = "disponible"
  case delivered = "entregado"
}

enum PackageStatusMapper {
SETS

  static func map(status: String, isAvailable: Bool, progress: Int) -> RemotePackageStage {
    let status = normalize(status)
    if deliveredTerms.contains(status) { return .delivered }
    if isAvailable { return .available }
    if matches(status, ["DISPONIBLE", "AVAILABLE"]) { return .destination }
    if matches(status, destinationTerms) { return .destination }
    if matches(status, routeTerms) { return .route }
    if matches(status, originTerms) { return .origin }
    switch progress {
    case ...1: return .origin
    case 2: return .route
    case 3, 4: return .destination
    default: return .delivered
    }
  }

  private static func matches(_ status: String, _ terms: Set<String>) -> Bool {
    terms.contains { (" " + status + " ").contains(" " + $0 + " ") }
  }

  private static func normalize(_ value: String) -> String {
    value.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "es"))
      .uppercased().components(separatedBy: CharacterSet.alphanumerics.inverted)
      .filter { !$0.isEmpty }.joined(separator: " ")
  }
}
'''.replace('SETS', swift_sets)
    kotlin = '''// Generated by tools/sync_package_status_native.py. Edit the Dart mapper.
package com.barolit.icourier.widget

import java.text.Normalizer
import java.util.Locale

internal enum class RemotePackageStage(val key: String) {
    ORIGIN("origen"), ROUTE("ruta"), DESTINATION("destino"),
    AVAILABLE("disponible"), DELIVERED("entregado"),
}

internal object PackageStatusMapper {
SETS

    fun map(status: String, isAvailable: Boolean, progress: Int): RemotePackageStage {
        val normalized = Normalizer.normalize(status, Normalizer.Form.NFD)
            .replace(Regex("\\\\p{M}+"), "").uppercase(Locale.ROOT)
            .replace(Regex("[^A-Z0-9]+"), " ").trim()
        fun matches(terms: Set<String>) = terms.any { " $it " in " $normalized " }
        return when {
            normalized in deliveredTerms -> RemotePackageStage.DELIVERED
            isAvailable -> RemotePackageStage.AVAILABLE
            matches(setOf("DISPONIBLE", "AVAILABLE")) -> RemotePackageStage.DESTINATION
            matches(destinationTerms) -> RemotePackageStage.DESTINATION
            matches(routeTerms) -> RemotePackageStage.ROUTE
            matches(originTerms) -> RemotePackageStage.ORIGIN
            progress <= 1 -> RemotePackageStage.ORIGIN
            progress == 2 -> RemotePackageStage.ROUTE
            progress <= 4 -> RemotePackageStage.DESTINATION
            else -> RemotePackageStage.DELIVERED
        }
    }
}
'''.replace('SETS', kotlin_sets)
    return {
        ROOT / 'ios/ICourierWidget/PackageStage.swift': swift,
        ROOT / 'android/app/src/main/kotlin/com/barolit/icourier/widget/PackageStage.kt': kotlin,
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    for path, content in generate().items():
        if options.check:
            assert path.read_text() == content, f'Run {__file__}: {path} is outdated'
        else:
            path.write_text(content)
        print(path.relative_to(ROOT))
